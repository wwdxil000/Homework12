public class Author {
    private String nameAuthor;
    private String surenameAuthor;

    public Author(String nameAuthor, String surenameAuthor) {
        this.nameAuthor = nameAuthor;
        this.surenameAuthor = surenameAuthor;
    }

    public String getNameAuthor() {
        return this.nameAuthor;
    }

    public String getSurenameAuthor() {
        return this.surenameAuthor;
    }
}
